export type Lang = 'en' | 'sv';

export const dictionaries: Record<Lang, Strings> = { en, sv };

export function strings(lang: Lang): Strings {
  return dictionaries[lang];
}

// Fills a template: {name} is replaced by the value; {name:one|other} is
// replaced by "one" when the value is exactly 1, and by "other" otherwise,
// so that every language words its own singular and plural.
export function format(template: string, values: Record<string, string | number>): string {
  return template
    .replace(/\{(\w+):([^|{}]*)\|([^{}]*)\}/g, (m, key: string, one: string, other: string) => (key in values ? (Number(values[key]) === 1 ? one : other) : m))
    .replace(/\{(\w+)\}/g, (m, key: string) => (key in values ? String(values[key]) : m));
}
